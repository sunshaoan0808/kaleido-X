  function renderAsVisual(data) {
    const el = $('as-visual');
    if (!el) return;
    const sessions = (data && data.sessions) || [];
    if (!sessions.length) {
      el.classList.add('hidden');
      return;
    }
    el.classList.remove('hidden');
    el.innerHTML = '<div class="as-visual-header"><span>Agent 会话列表 (' + sessions.length + ')</span></div>';
    for (const s of sessions) {
      const card = document.createElement('div');
      card.className = 'as-visual-card';
      const status = s.status || 'unknown';
      const statusCls = status === 'running' ? 'tag-running' : (status === 'done' ? 'tag-done' : 'tag-idle');
      card.innerHTML = [
        '<div class="as-vc-top">',
        '  <span class="as-vc-title">' + escapeHtml(s.title || '无标题') + '</span>',
        '  <span class="tag ' + statusCls + '">' + escapeHtml(status) + '</span>',
        '</div>',
        '<div class="as-vc-id">' + escapeHtml(s.id) + '</div>',
        '<div class="as-vc-meta">',
        '  <span>' + (s.messageCount || s.msgCount || 0) + ' 条消息</span>',
        '  <span>' + (s.createdAt ? new Date(s.createdAt).toLocaleString() : '') + '</span>',
        '</div>',
      ].join('');
      card.onclick = () => {
        if ($('as-id')) $('as-id').value = s.id;
        // Auto-load on click
        if ($('as-load')) $('as-load').click();
      };
      el.appendChild(card);
    }
  }

