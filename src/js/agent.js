  async function loadEmbedLabEvents() {
    const list = $('el-events-list');
    if (!list) return;
    const local = stL2Events(tavernSession);
    if (local.length) {
      renderEmbedLabEvents(local);
      return;
    }
    try {
      const data = await api('/api/v1/story-tavern/sessions');
      const sessions = (data && data.sessions) || [];
      for (const s of sessions) {
        const id = s.__ch().sessionId || s.id;
        if (!id) continue;
        let detail;
        try {
          detail = await api('/api/v1/story-tavern/sessions/' + encodeURIComponent(id));
        } catch (_) { continue; }
        const ev = stL2Events(detail);
        if (ev.length) {
          renderEmbedLabEvents(ev);
          return;
        }
      }
      renderEmbedLabEvents(null);
    } catch (e) {
      renderEmbedLabEvents(null);
      if ($('embedlab-msg')) $('embedlab-msg').textContent = '语义事件加载失败：' + (e.message || e);
    }
  }

  function renderEmbedLabMatrix(texts, vecs) {
    const n = texts.length;
    const matrix = $('embedlab-matrix');
    const pairs = $('embedlab-pairs');
    if (!matrix || !pairs) return;
    if (n < 2) {
      matrix.hidden = true;
      matrix.innerHTML = '';
      pairs.innerHTML = '';
      return;
    }
    let html = '<table><thead><tr><th></th>';
    for (let j = 0; j < n; j++) html += '<th title="' + texts[j].replace(/"/g, '&quot;') + '">#' + (j + 1) + '</th>';
    html += '</tr></thead><tbody>';
    const pairRows = [];
    for (let i = 0; i < n; i++) {
      html += '<tr><th title="' + texts[i].replace(/"/g, '&quot;') + '">#' + (i + 1) + ' ' + shortLabel(texts[i], 10) + '</th>';
      for (let j = 0; j < n; j++) {
        const s = cosineSim(vecs[i], vecs[j]);
        const cls = i === j ? 'diag' : heatClass(s);
        html += '<td class="' + cls + '" title="' + s.toFixed(4) + '">' + (i === j ? '1' : s.toFixed(2)) + '</td>';
        if (j > i) {
          pairRows.push({ i, j, s, a: texts[i], b: texts[j] });
        }
      }
      html += '</tr>';
    }
    html += '</tbody></table>';
    matrix.innerHTML = html;
    matrix.hidden = false;
    pairRows.sort((x, y) => y.s - x.s);
    pairs.innerHTML = pairRows.map((p) => {
      const pct = Math.max(0, Math.min(100, Math.round(((p.s + 1) / 2) * 100)));
      return (
        '<div class="embedlab-pair ' + heatClass(p.s) + '">' +
          '<div class="pair-score">' + p.s.toFixed(4) + '</div>' +
          '<div class="pair-body">' +
            '<div class="pair-line"><span class="idx">#' + (p.i + 1) + '</span> ' + shortLabel(p.a, 48) + '</div>' +
            '<div class="pair-line"><span class="idx">#' + (p.j + 1) + '</span> ' + shortLabel(p.b, 48) + '</div>' +
            '<div class="pair-bar"><i style="width:' + pct + '%"></i></div>' +
          '</div>' +
        '</div>'
      );
    }).join('');
  }

  async function runEmbedLab() {
    const raw = ($('embedlab-texts') && $('embedlab-texts').value) || '';
    const texts = raw.split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
    if (!texts.length) {
      if ($('embedlab-msg')) $('embedlab-msg').textContent = '至少输入 1 行文本';
      return;
    }
    if (texts.length > 12) {
      if ($('embedlab-msg')) $('embedlab-msg').textContent = '一次最多 12 行（避免刷爆）';
      return;
    }
    if ($('embedlab-run')) $('embedlab-run').disabled = true;
    if ($('embedlab-msg')) $('embedlab-msg').textContent = '计算中…';
    if ($('embedlab-meta')) $('embedlab-meta').textContent = '';
    const t0 = performance.now();
    try {
      const data = await api('/api/v1/embeddings', {
        method: 'POST',
        body: JSON.stringify({ input: texts, model: 'BAAI/bge-small-zh-v1.5' }),
      });
      const ms = Math.round(performance.now() - t0);
      const rows = (data && data.data) || [];
      const vecs = rows.map((r) => r.embedding || []);
      const dim = vecs[0] ? vecs[0].length : 0;
      const backend = (data && data.backend) || '—';
      if ($('embedlab-meta')) {
        $('embedlab-meta').textContent =
          backend + ' · dim ' + dim + ' · n=' + texts.length + ' · ' + ms + 'ms';
      }
      // refresh status pills from response if possible
      if ($('el-backend')) $('el-backend').textContent = backend;
      if ($('el-dim') && dim) $('el-dim').textContent = String(dim);
      if ($('el-ready')) {
        $('el-ready').textContent = '是';
        $('el-ready').classList.add('ok');
        $('el-ready').classList.remove('bad');
      }
      renderEmbedLabMatrix(texts, vecs);
      const preview = {
        backend,
        model: data && data.model,
        n: texts.length,
        dim,
        latency_ms: ms,
        first4: vecs[0] ? vecs[0].slice(0, 4) : null,
      };
      if ($('embedlab-out')) {
        $('embedlab-out').hidden = false;
        $('embedlab-out').textContent = JSON.stringify(preview, null, 2);
      }
      if ($('embedlab-msg')) {
        if (texts.length >= 2) {
          const best = cosineSim(vecs[0], vecs[1]);
          $('embedlab-msg').textContent =
            '完成。近义对应明显高过跨域（示例 #1↔#2 约 0.7，#1↔#3 约 0.25）。当前 #1↔#2 = ' +
            best.toFixed(4);
        } else {
          $('embedlab-msg').textContent = '完成（单条，无 pairwise）';
        }
      }
    } catch (e) {
      if ($('embedlab-msg')) $('embedlab-msg').textContent = '失败：' + (e.message || e);
      if ($('embedlab-out')) {
        $('embedlab-out').hidden = false;
        $('embedlab-out').textContent = String(e.message || e);
      }
    } finally {
      if ($('embedlab-run')) $('embedlab-run').disabled = false;
    }
  }

